// generated heads every generated page: the word that wrote it and from
// what, so a reader knows not to edit it.
func generated(word, from string) string {
	return "<!-- Generated by the site skill's " + word + " word from " + from + ". Regenerate it; do not edit it. -->\n"
}

// StatusInput is what the status pages are made from: the system checkout,
// the reports checkout, the timeline's sources, and the tracker when one is
// reachable.
type StatusInput struct {
	Reports, System string
	Sources         TimelineSources
	Tracker         tracker.Tracker
	// Projects are the program's repositories, the system's first.
	Projects []string
	Policy   program.Policy
}

// LoadStatusInput reads what the status pages need: the timeline's sources,
// the program's repositories, and its policy, from the system checkout
// through the tracker when one is reachable, else the defaults.
func LoadStatusInput(reportsDir, system string, t tracker.Tracker, today time.Time) (StatusInput, error) {
	in := StatusInput{Reports: reportsDir, System: system, Tracker: t, Policy: program.Defaults()}
	var err error
	if in.Sources, err = LoadSources(system, t, today); err != nil {
		return in, err
	}
	if in.Projects, err = Projects(system); err != nil {
		return in, err
	}
	if t != nil && in.Projects[0] != "" {
		if p, err := program.LoadPolicy(t, in.Projects[0], "main"); err == nil {
			in.Policy = p
		}
	}
	return in, nil
}

// StatusPages are the status word's pages under site/status/ and the facts
// behind each under site/data/status/ (srd048 R4): the road map, the
// story-point roll-up, the architecture status, the Sprint Goals, the
// signals, and the open issues. Each reuses the words' own facts; none is
// derived again here.
func StatusPages(in StatusInput) (pages, data map[string][]byte, notes []string, err error) {
	pages, data = map[string][]byte{}, map[string][]byte{}
	pages[Dir+"/status/index.md"] = []byte(statusIndex())
	add := func(name, page string, facts any) {
		pages[Dir+"/status/"+name+".md"] = []byte(page)
		b, _ := json.MarshalIndent(facts, "", "  ")
		data[Dir+"/data/status/"+name+".json"] = append(b, '\n')
	}
	roadMap, err := os.ReadFile(filepath.Join(in.System, "docs", "road-map.md"))
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return nil, nil, nil, err
	}
	releases := Releases(roadMap, in.Sources)
	add("road-map", roadMapPage(releases), releases)

	docs, err := hierarchy.Load(in.System)
	if err != nil {
		return nil, nil, nil, err
	}
	done, err := sprintgoal.StoriesDone(in.System)
	if err != nil {
		return nil, nil, nil, err
	}
	doneSet := map[string]bool{}
	for id := range done.Release {
		doneSet[id] = true
	}
	progress, external := hierarchy.RollUp(docs, doneSet)
	// The team checkouts beside the system's add their stories to the
	// documents they serve, as backlog status counts them (GH-109).
	teams, _ := backlog.TeamProgress(in.Sources.Teams, docs)
	for i, p := range progress {
		if t, ok := teams[p.ID]; ok {
			progress[i].Done += t.Done
			progress[i].Total += t.Total
			delete(teams, p.ID)
		}
	}
	for id, t := range teams {
		progress = append(progress, hierarchy.Progress{ID: id, Kind: t.Kind, Done: t.Done, Total: t.Total})
	}
	slices.SortFunc(progress, func(a, b hierarchy.Progress) int { return strings.Compare(a.ID, b.ID) })
	add("roll-up", rollUpPage(docs, progress, external), struct {
		Progress []hierarchy.Progress `json:"progress"`
		External []string             `json:"external,omitempty"`
	}{progress, external})

	view, err := backlog.Architecture(in.System)
	if err != nil {
		return nil, nil, nil, err
	}
	add("architecture", archLinks(view.Page(), in.System, in.Reports), view)

	if in.Tracker == nil {
		const none = "No tracker was reachable when this page was generated, so it lists nothing; regenerate it where the program's tracker is.\n"
		add("sprint-goals", generated("status", "the Sprint Goals' ledgers")+"# Sprint Goals\n\n"+none, []sprintend.SprintGoal{})
		add("signals", generated("status", "the weekly reports' aggregate")+"# Signals\n\n"+none, reports.Aggregation{})
		page, rollup, err := latestRollupPage(in.System)
		if err != nil {
			return nil, nil, nil, err
		}
		add("rollup", page, rollup)
		add("issues", generated("status", "the tracker's open issues")+"# Open issues\n\n"+none, []tracker.Issue{})
		return pages, data, []string{"no tracker reachable: the Sprint Goals, signals, and open issues pages list nothing"}, nil
	}
	from, to := period(releases, in.Sources)
	agg := reports.Aggregation{From: from, To: to, ByComponent: map[string][]string{}, Signals: []reports.Signal{}, Progress: []reports.Progress{}}
	system := ""
	if len(in.Projects) > 0 {
		system = in.Projects[0]
	}
	// With the roster in the system repository, the program's reports are
	// collected where they were written (srd018 R13, R17; GH-2725).
	if cfg, err := reports.LoadControl(in.Tracker, system, "main"); err == nil {
		col, err := reports.Collect(in.Tracker, reports.CollectInput{Config: cfg, System: system, Ref: "main", Level: reports.ProgramLevel, From: from, To: to})
		if err != nil {
			return nil, nil, nil, err
		}
		for _, u := range col.Unread {
			notes = append(notes, fmt.Sprintf("%s: %s", u.Repository, u.Reason))
		}
		if agg, err = reports.Aggregate(in.Tracker, reports.AggregateInput{Config: cfg, Policy: in.Policy, From: from, To: to, Now: in.Sources.Today, Collection: &col}); err != nil {
			return nil, nil, nil, err
		}
		add("signals", signalsPage(agg), agg)
	} else if cfg, err := reports.LoadConfig(in.Reports); err != nil {
		// A checkout that is no reports repository has no reports to
		// aggregate; the page says so rather than the run failing.
		notes = append(notes, "no reports configuration: "+err.Error())
		add("signals", generated("status", "the weekly reports' aggregate")+"# Signals\n\nThe reports checkout has no reports.md, so there are no weekly reports to read.\n", agg)
	} else {
		if agg, err = reports.Aggregate(in.Tracker, reports.AggregateInput{Dir: in.Reports, Config: cfg, Policy: in.Policy, From: from, To: to, Now: in.Sources.Today}); err != nil {
			return nil, nil, nil, err
		}
		add("signals", signalsPage(agg), agg)
	}
	tags, err := CorpusTags(in.System)
	if err != nil {
		return nil, nil, nil, err
	}
	project := ""
	if len(in.Projects) > 0 {
		project = in.Projects[0]
	}
	facts, err := sprintend.MakeFacts(sprintend.Input{Tracker: in.Tracker, Project: project, Teams: in.Projects[min(1, len(in.Projects)):],
		Aggregate: agg, Releases: in.Policy.Releases, Artifact: "corpus", Tags: tags, Dir: in.System})
	if err != nil {
		return nil, nil, nil, err
	}
	add("sprint-goals", sprintGoalsPage(facts.SprintGoals, from, to), facts.SprintGoals)
	rollupPage, rollup, err := latestRollupPage(in.System)
	if err != nil {
		return nil, nil, nil, err
	}
	add("rollup", rollupPage, rollup)
	var open []tracker.Issue
	for _, p := range in.Projects {
		issues, err := in.Tracker.ListIssues(p, tracker.IssueQuery{State: "opened"})
		if err != nil {
			notes = append(notes, fmt.Sprintf("%s: %v", p, err))
			continue
		}
		open = append(open, issues...)
	}
	add("issues", issuesPage(open), open)
	return pages, data, notes, nil
}

// archRelLink is a docs-relative Markdown link on the architecture-status
// page: a bare file name, as a page written for docs/ links its neighbors.
var archRelLink = regexp.MustCompile(`\[([^\]]+)\]\(([A-Za-z0-9._-]+\.md)\)`)

// archLinks re-aims the architecture-status page's docs-relative links for
// site/status/: the page is the word's own (srd045 R8.5), written for
// docs/, where ARCHITECTURE.md sits beside it, and under the site the
// document's copy is in ../corpus/. When the corpus is withheld (an
// encrypted program, GH-115) the forge serves it, and with no forge the
// link is left as written (GH-122).
func archLinks(page, system, reports string) string {
	target := "../corpus/"
	if withheld(system, reports) != "" {
		target = blobBase(system)
		if target != "" {
			target += "docs/"
		}
	}
	// A document the system repository does not hold, or one with no
	// place to point at, is named without a link, which would be dead
	// (GH-139).
	return archRelLink.ReplaceAllStringFunc(page, func(m string) string {
		sub := archRelLink.FindStringSubmatch(m)
		text, name := sub[1], sub[2]
		if _, err := os.Stat(filepath.Join(system, "docs", name)); err != nil || target == "" {
			return text
		}
		return "[" + text + "](" + target + name + ")"
	})
}

// period is the sprint the status pages report on, as ISO weeks: the
// release's whose sprint holds today, else the latest begun; this week
// alone when no release has a sprint.
func period(releases []timeline.Release, s TimelineSources) (from, to string) {
	today := s.Today.Format(time.DateOnly)
	var current *timeline.Span
	for _, r := range releases {
		if r.Sprint != nil && r.Sprint.Start <= today {
			current = r.Sprint
			if today <= r.Sprint.End {
				break
			}
		}
	}
	if current == nil {
		w := reports.ISOWeek(s.Today)
		return w, w
	}
	start, _ := time.Parse(time.DateOnly, current.Start)
	end, _ := time.Parse(time.DateOnly, current.End)
	return reports.ISOWeek(start), reports.ISOWeek(end)
}

// statusIndex is the status folder's page, linking each status page.
// statusIndex links each page and each page's facts file: a link to the
// facts' folder resolves, in the app, to an index the folder does not
// have (GH-139).
func statusIndex() string {
	return generated("status", "the status pages it links") + `# Status

- [Road map](road-map.md): each release, its status, tag, milestone, and sprint
- [Story-point roll-up](roll-up.md): points done over total for each theme, initiative, epic, and feature
- [Architecture](architecture.md): what exists, what is being built and when it lands, and what is intended
- [Sprint Goals](sprint-goals.md): each Sprint Goal's ledger and outcome
- [Program rollup](rollup.md): the program's latest rollup, its headlines, progress, risks and asks, each claim citing its source
- [Signals](signals.md): what the weekly reports say needs attention
- [Open issues](issues.md): every open issue, by plane, kind, and state

The facts behind each page are JSON beside the site: [road map](../data/status/road-map.json), [roll-up](../data/status/roll-up.json), [architecture](../data/status/architecture.json), [Sprint Goals](../data/status/sprint-goals.json), [program rollup](../data/status/rollup.json), [signals](../data/status/signals.json), and [open issues](../data/status/issues.json).
`
}

func roadMapPage(releases []timeline.Release) string {
	var b strings.Builder
	b.WriteString(generated("status", "docs/road-map.md and the program's milestones") + "# Road map\n\nEach release, its status, its tag and milestone, its sprint, and the initiative items it proves.\n\n")
	if len(releases) == 0 {
		b.WriteString("No release yet.\n")
		return b.String()
	}
	// The figure is the app's; the forge strips the iframe and the table
	// below carries the same facts (GH-131).
	b.WriteString(embed("roadmap", "The program's interactive road map") + "\n")
	b.WriteString("| release | status | tag | milestone | sprint | items |\n| --- | --- | --- | --- | --- | --- |\n")
	for _, r := range releases {
		sprint := ""
		if r.Sprint != nil {
			sprint = r.Sprint.Start + " to " + r.Sprint.End
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s |\n", r.Version, r.Status, r.Tag, r.Milestone, sprint, strings.Join(r.Items, ", "))
	}
	return b.String()
}

func rollUpPage(docs []*hierarchy.Doc, progress []hierarchy.Progress, external []string) string {
	titles := map[string]string{}
	for _, d := range docs {
		titles[d.ID] = d.Title
	}
	var b strings.Builder
	b.WriteString(generated("status", "the hierarchy documents and the sprint-end summaries") + "# Story-point roll-up\n\nPoints done over total for each theme, initiative, epic, and feature, from its agreed stories, the team checkouts' agreed stories that serve it, and the stories the sprint-end summaries record done.\n\n")
	if len(progress) == 0 {
		b.WriteString("No document to roll up yet.\n")
	} else {
		b.WriteString("| document | kind | title | done | total |\n| --- | --- | --- | --- | --- |\n")
		for _, p := range progress {
			fmt.Fprintf(&b, "| %s | %s | %s | %d | %d |\n", p.ID, p.Kind, titles[p.ID], p.Done, p.Total)
		}
	}
	if len(external) > 0 {
		fmt.Fprintf(&b, "\nStories whose parent is in another repository, rolled up there: %s.\n", strings.Join(external, ", "))
	}
	return b.String()
}

func sprintGoalsPage(goals []sprintend.SprintGoal, from, to string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s# Sprint Goals\n\nEach Sprint Goal with its ledger and outcome, for the sprint from %s to %s. Reported complete is the owner's word; met needs evidence (srd038 R2.2).\n\n", generated("status", "the Sprint Goals' ledgers"), from, to)
	if len(goals) == 0 {
		b.WriteString("No Sprint Goal yet.\n")
		return b.String()
	}
	// The status its owner last reported, at-risk among them, is the
	// page's to show beside the issue's state (GH-141).
	b.WriteString("| Sprint Goal | release | title | state | reported | outcome | ledger |\n| --- | --- | --- | --- | --- | --- | --- |\n")
	for _, g := range goals {
		reported := g.Reported
		if reported == "" {
			reported = "not reported"
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s |\n", g.Issue, g.Release, g.Title, g.State, reported, g.Outcome, strings.Join(g.Ledger, "; "))
	}
	return b.String()
}

func signalsPage(agg reports.Aggregation) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s# Signals\n\nWhat the weekly reports from %s to %s say needs attention: %d reports read.\n\n", generated("status", "the weekly reports' aggregate"), agg.From, agg.To, agg.Reports)
	if len(agg.Signals) == 0 {
		b.WriteString("No signal.\n")
		return b.String()
	}
	b.WriteString("| week | kind | component | detail |\n| --- | --- | --- | --- |\n")
	for _, s := range agg.Signals {
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", s.Week, s.Kind, s.Component, s.Detail)
	}
	return b.String()
}

func issuesPage(open []tracker.Issue) string {
	var b strings.Builder
	b.WriteString(generated("status", "the tracker's open issues") + "# Open issues\n\nEvery open issue of the program's repositories, by plane, kind, state, and op.\n\n")
	if len(open) == 0 {
		b.WriteString("No open issue.\n")
		return b.String()
	}
	axis := func(i tracker.Issue, prefix string) string {
		for _, l := range i.Labels {
			if v, ok := strings.CutPrefix(l, prefix); ok {
				return v
			}
		}
		return ""
	}
	slices.SortFunc(open, func(a, b tracker.Issue) int {
		return strings.Compare(axis(a, "plane::")+axis(a, "kind::")+axis(a, "op::")+a.Project, axis(b, "plane::")+axis(b, "kind::")+axis(b, "op::")+b.Project)
	})
	b.WriteString("| issue | title | plane | kind | state | op | milestone |\n| --- | --- | --- | --- | --- | --- | --- |\n")
	for _, i := range open {
		state := axis(i, "status::")
		if state == "" {
			state = "open"
		}
		fmt.Fprintf(&b, "| %s#%d | %s | %s | %s | %s | %s | %s |\n", i.Project, i.IID, i.Title, axis(i, "plane::"), axis(i, "kind::"), state, axis(i, "op::"), i.Milestone)
	}
	return b.String()
}

// embed is the interactive timeline page embedded in a site page, in its
// timeline or road map view. The source is site-rooted, as the app shell
// resolves it from any route; the forge strips it (GH-131).
func embed(view, title string) string {
	return fmt.Sprintf(`<iframe class="timeline" src="%s/program.html?embed=1&view=%s" title="%s"></iframe>`, GanttDir, view, title) + "\n"
}

// latestRollupPage is the program's latest rollup as a status page: the
// rollup the technical program manager merged in the system repository,
// shown as written, with its facts (srd018 R15, srd048 R4; GH-2725).
func latestRollupPage(system string) (string, *reports.Rollup, error) {
	head := generated("status", "the system repository's latest program rollup") + "# Program rollup\n\n"
	p := reports.LatestProgramRollup(system)
	if p == "" {
		return head + "No program rollup has merged yet: the status-rollup skill writes one each week in the system repository's status/rollups/.\n", nil, nil
	}
	b, err := os.ReadFile(p)
	if err != nil {
		return "", nil, err
	}
	rel, _ := filepath.Rel(system, p)
	r, err := reports.ParseRollup(filepath.ToSlash(rel), b)
	if err != nil {
		return head + fmt.Sprintf("%s does not read as a rollup: %v\n", filepath.ToSlash(rel), err), nil, nil
	}
	var page strings.Builder
	page.WriteString(head)
	fmt.Fprintf(&page, "Written by %s for %s, from %s in the system repository.\n\n", r.FrontMatter.Author, r.FrontMatter.Period, filepath.ToSlash(rel))
	_, body, _ := strings.Cut(strings.TrimPrefix(string(b), "---\n"), "\n---\n")
	page.WriteString(strings.TrimLeft(body, "\n"))
	return page.String(), &r, nil
}
