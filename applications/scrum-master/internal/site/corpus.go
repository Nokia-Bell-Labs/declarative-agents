// CorpusDir is the corpus word's folder: the system repository's docs/, as
// pages.
const CorpusDir = "corpus"

// link is a Markdown link or image target: the text in the parentheses
// after the brackets, up to a space or the closing parenthesis.
var link = regexp.MustCompile(`(\]\()([^)\s]+)`)

// blobBase is where a forge shows the system repository's files at its
// default branch, so a link the site cannot hold points at the forge: under
// SCRUM_MASTER_WEB_BASE, the web root the program's citations use, when it
// is set and the origin names a project (GH-141), else from the origin as
// configured; empty when neither is one a browser opens.
func blobBase(system string) string {
	origin := originWeb(system)
	if base := strings.TrimSuffix(strings.TrimSpace(os.Getenv("SCRUM_MASTER_WEB_BASE")), "/"); base != "" && origin != "" { //nolint:forbidigo // Reads the documented SCRUM_MASTER_* environment interface.
		origin = base + "/" + program.ProjectPath(origin)
	}
	if origin == "" {
		return ""
	}
	if strings.Contains(origin, "github.com/") {
		return origin + "/blob/HEAD/"
	}
	return origin + "/-/blob/HEAD/"
}

// originWeb is the repository's page on its forge, from the origin as
// configured: an https origin as it is, an scp-style ssh one rewritten to
// https, without .git; empty for any other origin (GH-127).
func originWeb(dir string) string {
	out, _ := exec.Command("git", "-C", dir, "config", "--get", "remote.origin.url").Output()
	origin := strings.TrimSuffix(strings.TrimSpace(string(out)), ".git")
	if strings.HasPrefix(origin, "git@") {
		if host, p, ok := strings.Cut(strings.TrimPrefix(origin, "git@"), ":"); ok {
			origin = "https://" + host + "/" + p
		}
	}
	if !strings.HasPrefix(origin, "https://") {
		return ""
	}
	return origin
}

// fixLinks keeps a page's relative links that land inside docs/, which the
// site holds at the same relative places, and points those that leave it
// at the forge, or leaves them as written when there is no forge to point
// at (srd048 R7.1). Absolute links and anchors are left as they are.
func fixLinks(page []byte, rel, base string) []byte {
	return link.ReplaceAllFunc(page, func(m []byte) []byte {
		sub := link.FindSubmatch(m)
		target := string(sub[2])
		if target == "" || strings.HasPrefix(target, "#") || strings.Contains(target, "://") || strings.HasPrefix(target, "mailto:") || strings.HasPrefix(target, "/") {
			return m
		}
		file, anchor, _ := strings.Cut(target, "#")
		resolved := path.Clean(path.Join(path.Dir(rel), file))
		if strings.HasPrefix(resolved, "docs/") || base == "" {
			return m
		}
		if anchor != "" {
			anchor = "#" + anchor
		}
		return []byte(string(sub[1]) + base + resolved + anchor)
	})
}

// historySection is a document's changes across corpus tags, closing its
// corpus page (srd048 R7.1, GH-96): the history word's rows for it, newest
// first, with a link to its page in the history. A move between releases
// is on both the moved item's document and the road map it was made in
// (GH-116); only a document's own changes link its history page.
func historySection(inside string, steps []Step) string {
	var rows []string
	doc := ""
	for i := len(steps) - 1; i >= 0; i-- {
		for _, c := range steps[i].Changes {
			own := c.Path == "docs/"+inside
			if own || c.Via == "docs/"+inside {
				if own {
					doc = c.Document
				}
				line := strings.TrimPrefix(changeLine(c), "- ")
				if !own {
					line = c.Document + " " + line
				}
				rows = append(rows, fmt.Sprintf("- %s to %s: %s", steps[i].From, steps[i].To, line))
			}
		}
	}
	if len(rows) == 0 {
		return ""
	}
	head := "\n## History\n\nThis document's requirements and acceptance criteria as they changed between corpus tags, newest first, generated by the site from local git"
	if doc != "" {
		link, _ := filepath.Rel(path.Dir(CorpusDir+"/"+inside), "history/docs/"+doc+".md")
		head += " ([its history](" + filepath.ToSlash(link) + "))"
	}
	return head + ".\n\n" + strings.Join(rows, "\n") + "\n"
}

// CorpusPages are the corpus word's pages (srd048 R7.1): every Markdown
// document under the system checkout's docs/, at the same place under
// site/corpus/, with an index listing them; links within docs/ resolve in
// the site, links leaving it point at the forge, and a document the history
// names closes with its changes across tags.
func CorpusPages(system string, steps []Step) (map[string][]byte, error) {
	pages := map[string][]byte{}
	base := blobBase(system)
	var listed []string
	titles := map[string]string{}
	err := filepath.WalkDir(filepath.Join(system, "docs"), func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(p, ".md") {
			return err
		}
		rel, err := filepath.Rel(system, p)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		inside := strings.TrimPrefix(rel, "docs/")
		page := fixLinks(b, rel, base)
		if h := historySection(inside, steps); h != "" {
			page = append(append(bytes.TrimRight(page, "\n"), '\n'), h...)
		}
		pages[Dir+"/"+CorpusDir+"/"+inside] = page
		listed = append(listed, inside)
		if md, err := corpus.ParseMarkdown(b); err == nil {
			if t, ok := md.Front["title"].(string); ok {
				titles[inside] = t
			}
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	slices.Sort(listed)
	var index strings.Builder
	index.WriteString(generated("corpus pages", "the system repository's docs/") + "# Corpus\n\nThe program's documents as the system repository holds them: its vision, architecture, road map, requirements, and planning hierarchy. Each page is a copy, regenerated from the repository; change the repository's document, not the page.\n\n")
	if len(listed) == 0 {
		index.WriteString("No document yet.\n")
	}
	for _, p := range listed {
		if p == "index.md" {
			continue
		}
		title := titles[p]
		if title == "" {
			title = strings.TrimSuffix(path.Base(p), ".md")
		}
		fmt.Fprintf(&index, "- [%s](%s)\n", title, p)
	}
	if _, clash := pages[Dir+"/"+CorpusDir+"/index.md"]; !clash {
		pages[Dir+"/"+CorpusDir+"/index.md"] = []byte(index.String())
	}
	return pages, nil
}

// HistorySteps reads the history word's steps from the reports checkout dir;
// none when the history word has not run.
func HistorySteps(dir string) ([]Step, error) {
	b, err := os.ReadFile(filepath.Join(dir, Dir, "data", "history", "history.json"))
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	} else if err != nil {
		return nil, err
	}
	var steps []Step
	return steps, json.Unmarshal(b, &steps)
}

// PublishTree publishes pages under root, a folder of the site whose
// subfolders are all its own, one folder at a time, so a folder whose
// pages are all gone is pruned too.
func PublishTree(dir, root string, pages map[string][]byte, version string, dryRun bool) ([]Page, error) {
	folders := map[string]map[string][]byte{}
	for p, b := range pages {
		f := strings.TrimPrefix(path.Dir(p), Dir+"/")
		if folders[f] == nil {
			folders[f] = map[string][]byte{}
		}
		folders[f][p] = b
	}
	_ = filepath.WalkDir(filepath.Join(dir, Dir, root), func(p string, d fs.DirEntry, err error) error {
		if err == nil && d.IsDir() {
			if rel, err := filepath.Rel(filepath.Join(dir, Dir), p); err == nil && folders[filepath.ToSlash(rel)] == nil {
				folders[filepath.ToSlash(rel)] = map[string][]byte{}
			}
		}
		return nil
	})
	names := make([]string, 0, len(folders))
	for f := range folders {
		names = append(names, f)
	}
	slices.Sort(names)
	var out []Page
	for _, f := range names {
		published, err := Publish(dir, f, folders[f], version, dryRun)
		out = append(out, published...)
		if err != nil {
			return out, err
		}
	}
	return out, nil
}
