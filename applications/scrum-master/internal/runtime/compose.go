// Composition is how to build the agent that serves the words in its own
// process (GH-27): agent-core's cmd/agent, unchanged on disk, built in a
// workspace with this application and with one more file overlaid into it,
// which registers words.Run under words.Binary with agent-core's
// in-process exec transport. Env and Flags go to the go build; Cleanup
// removes the workspace and the overlay. Dir is the agent-core directory
// to build in: core with its symbolic links resolved, as the go command
// resolves its working directory against the workspace.
type Composition struct {
	Dir     string
	Env     []string
	Flags   []string
	Cleanup func()
}

// registration is the file overlaid into agent-core's cmd/agent. The
// module paths are read from the two go.mod files, not written here.
const registration = `// Code generated by the scrum-master agent build (GH-27). DO NOT EDIT.

package main

import (
	"context"

	"%[1]s/cmd/agent/internal/scrummasterspec"
	"%[1]s/pkg/inprocess"
	"%[2]s/words"
)

func init() {
	inprocess.Register(words.Binary, func(_ context.Context, c inprocess.Call) int {
		return words.RunIn(c.Dir, c.Args, c.Stdin, c.Out)
	})
	words.SetSpecTool(scrummasterspec.Run)
}
`

// specPackage is where the overlay puts the spec tool's program, as a
// package of agent-core's cmd/agent (GH-33).
const specPackage = "scrummasterspec"

// Compose prepares the composed build of the agent in core, the agent-core
// module, with the words of app, this application's module.
func Compose(core, app string) (Composition, error) {
	var err error
	if core, err = filepath.EvalSymlinks(core); err != nil {
		return Composition{}, err
	}
	if app, err = filepath.EvalSymlinks(app); err != nil {
		return Composition{}, err
	}
	coreMod, coreGo, err := readGoMod(core)
	if err != nil {
		return Composition{}, err
	}
	appMod, appGo, err := readGoMod(app)
	if err != nil {
		return Composition{}, err
	}
	dir, err := os.MkdirTemp("", "scrum-master-agent-*")
	if err != nil {
		return Composition{}, err
	}
	cleanup := func() { os.RemoveAll(dir) }
	work := fmt.Sprintf("go %s\n\nuse (\n\t%s\n\t%s\n)\n", laterGo(coreGo, appGo), core, app)
	file := filepath.Join(dir, "zz_scrum_master_words.go")
	spec := filepath.Join(dir, specPackage+".go")
	overlay, err := json.Marshal(map[string]map[string]string{"Replace": {
		filepath.Join(core, "cmd", "agent", filepath.Base(file)):                        file,
		filepath.Join(core, "cmd", "agent", "internal", specPackage, specPackage+".go"): spec,
	}})
	if err == nil {
		err = os.WriteFile(filepath.Join(dir, "go.work"), []byte(work), 0o644)
	}
	if err == nil {
		err = os.WriteFile(file, []byte(fmt.Sprintf(registration, coreMod, appMod)), 0o644)
	}
	if err == nil {
		err = os.WriteFile(spec, []byte(spectool.Program(specPackage, coreMod)), 0o644)
	}
	if err == nil {
		err = os.WriteFile(filepath.Join(dir, "overlay.json"), overlay, 0o644)
	}
	if err != nil {
		cleanup()
		return Composition{}, err
	}
	return Composition{
		Dir:     core,
		Env:     []string{"GOWORK=" + filepath.Join(dir, "go.work")},
		Flags:   []string{"-overlay", filepath.Join(dir, "overlay.json")},
		Cleanup: cleanup,
	}, nil
}

// readGoMod returns the module path and go version dir's go.mod declares.
func readGoMod(dir string) (module, goVersion string, err error) {
	b, err := os.ReadFile(filepath.Join(dir, "go.mod"))
	if err != nil {
		return "", "", err
	}
	for _, line := range strings.Split(string(b), "\n") {
		line = strings.TrimSpace(line)
		if m, ok := strings.CutPrefix(line, "module "); ok {
			module = strings.TrimSpace(m)
		} else if v, ok := strings.CutPrefix(line, "go "); ok {
			goVersion = strings.TrimSpace(v)
		}
	}
	if module == "" || goVersion == "" {
		return "", "", fmt.Errorf("%s/go.mod declares no module or no go version", dir)
	}
	return module, goVersion, nil
}

// laterGo is the later of two go versions such as 1.26 and 1.26.3: a
// workspace must declare at least each module's.
func laterGo(a, b string) string {
	pa, pb := strings.Split(a, "."), strings.Split(b, ".")
	for i := 0; i < max(len(pa), len(pb)); i++ {
		var x, y int
		if i < len(pa) {
			x, _ = strconv.Atoi(pa[i])
		}
		if i < len(pb) {
			y, _ = strconv.Atoi(pb[i])
		}
		if x != y {
			if x > y {
				return a
			}
			return b
		}
	}
	return a
}
